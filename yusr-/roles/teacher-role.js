// المعلم المستقل يبقى بصلاحيات كاملة كما طلبت، ولا يتم تقييده بصلاحيات المشرف.

export function isIndependentTeacherAccount(license = null) {
  return Boolean(license?.accessMode === "teacher" && !normalizeCode(license?.parentCode));
}

